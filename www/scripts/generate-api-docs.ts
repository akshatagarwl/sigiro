/**
 * Writes the API reference pages from openapi.json — the same document sigiro
 * serves at /openapi.json and tells agents to read. The spec is a committed
 * snapshot so the build never depends on a running server; refresh it with
 * `just api-spec` when the surface changes.
 *
 * Each page is a small MDX file: frontmatter for the title and description, the
 * operation's description as markdown so it renders through the same pipeline as
 * every other doc, and one <ApiOperation /> call for the mechanical part. No
 * schema-to-markup generation happens here — see components/api-operation.tsx,
 * which reads the spec directly.
 *
 * Run: bun run api:docs
 */
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { operations } from '../src/lib/api-spec';

const CONTENT = './content/docs/api';
const ROUTES = './src/app/docs/api';

/** Frontmatter is YAML and these descriptions carry colons, quotes and dashes. */
function yamlString(value: string): string {
  return JSON.stringify(value.replace(/\s+/g, ' ').trim());
}

/**
 * A frontmatter description is read as plain text — under the page title and in
 * <meta name="description"> — so the markdown a spec description carries would
 * show up as literal backticks in both. The body keeps its markdown.
 */
function plain(markdown: string): string {
  return markdown.replaceAll('`', '');
}

/**
 * Reading order, which is the order of the loop the product describes: find a
 * service, see what changed, ask why, drill into it, then read one trace. Not
 * alphabetical, and not the order the spec happens to list them in. An id missing
 * from here still ships — it lands at the end rather than disappearing.
 */
const ORDER = ['list-services', 'list-anomalies', 'investigate-services', 'run-query', 'get-trace'];

const rank = (id: string) => {
  const i = ORDER.indexOf(id);
  return i === -1 ? ORDER.length : i;
};

const ops = operations().sort((a, b) => rank(a.id) - rank(b.id));

await rm(CONTENT, { recursive: true, force: true });
await mkdir(CONTENT, { recursive: true });

for (const op of ops) {
  await writeFile(
    `${CONTENT}/${op.id}.mdx`,
    `---
title: ${yamlString(op.summary)}
description: ${yamlString(plain(op.description))}
# The sections come from <ApiOperation />, not from markdown headings, so the table
# of contents has nothing to list. full gives that column's width to the content
# instead of reserving it empty.
full: true
---

{/* Generated by scripts/generate-api-docs.ts from openapi.json. Do not edit. */}

<ApiOperation id="${op.id}" />
`,
  );
}

await writeFile(
  `${CONTENT}/index.mdx`,
  `---
title: API reference
description: ${yamlString('Every endpoint sigiro answers on, generated from the spec an agent reads.')}
---

{/* Generated by scripts/generate-api-docs.ts from openapi.json. Do not edit. */}

Five endpoints. Every field and constraint is in
[/openapi.json](https://api.sigiro.com/openapi.json), which is the document these
pages are generated from — an agent needs nothing else from us to get started.

## Endpoints

<Cards>
${ops
  .map(
    (op) =>
      `<Card href="/docs/api/${op.id}" title=${yamlString(op.summary)} description=${yamlString(`${op.method} ${op.path}`)} />`,
  )
  .join('\n')}
</Cards>
`,
);

await writeFile(
  `${CONTENT}/meta.json`,
  // Without a title fumadocs names the section after the directory — "Api". The
  // index page is deliberately not listed: the folder itself links to it, and
  // listing it too put "API reference" in the sidebar twice.
  `${JSON.stringify({ title: 'API reference', root: false, pages: ops.map((o) => o.id) }, null, 2)}\n`,
);

/**
 * A route file per operation. Under vinext `generateMetadata` has its tags streamed
 * into <body> — sync or async — where a crawler that does not run JavaScript never
 * sees them; only a static `metadata` export reaches <head>. Rather than
 * hand-maintaining five near-identical route files, they are written from the same
 * spec that writes the pages.
 */
for (const op of ops) {
  await rm(`${ROUTES}/${op.id}`, { recursive: true, force: true });
  await mkdir(`${ROUTES}/${op.id}`, { recursive: true });
  await writeFile(
    `${ROUTES}/${op.id}/page.tsx`,
    `// Generated by scripts/generate-api-docs.ts. Do not edit.
import { DocRoute } from '@/components/doc-route';
import { source } from '@/lib/source';

const page = source.getPage(['api', '${op.id}'])!;

export const dynamic = 'force-static';

export const metadata = {
  title: page.data.title,
  description: page.data.description,
  alternates: { canonical: page.url },
};

export default function Page() {
  return <DocRoute page={page} />;
}
`,
  );
}

console.log(`API reference: ${ops.length} operations, pages + routes written`);
