/**
 * Everything on the landing page that is NOT copy.
 *
 * This file exists so a translation cannot reach the things that must be
 * byte-identical in every locale. It is not a tidiness split: `HOW` and `LOOP`
 * interleave prose with real shell sessions, and a translated `docker run` or a
 * localized `SELECT` is a page that lies about what the product does. Keeping
 * those values in one module makes that failure structurally impossible rather
 * than something a reviewer has to catch — and no reviewer here reads all three
 * target languages.
 *
 * What lives here:
 *
 * - **Shell commands and their output** (`cmd`, `out`). Every transcript on the
 *   page. `HowItWorks.astro` runs these through Shiki at build time, and
 *   `lib/highlight.ts` notes that a bad transcript is a failure only a literal
 *   can cause — so the literals are shared.
 * - **Identifiers the code branches on**: variant `id`, `LOOP[].ours`,
 *   `artifact.lang`, icon slugs. A translated `id` breaks the localStorage
 *   handshake with the docs; a translated `lang` breaks highlighting; a
 *   translated icon slug renders no mark.
 * - **URLs and product names.** Brands are written verbatim in Chinese, Japanese
 *   and Korean technical documentation, so translating them would be wrong even
 *   if it were safe.
 * - **The analytics token**, which is one value for the whole site.
 *
 * Copy lives in `site.<locale>.ts`. The two are joined by `site.ts`.
 */

